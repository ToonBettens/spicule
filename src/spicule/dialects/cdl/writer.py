"""The CDL writer: a validated netlist as a CDL netlist."""

from spicule.dialects.cdl.syntax import BUILTINS, BUS_FORMAT, FUNCTIONS, LETTERS
from spicule.dialects.common import NetNames, WriterError
from spicule.ir import (
    Cell,
    Element,
    Expression,
    External,
    Instance,
    Netlist,
    Number,
    ParamDecl,
    ParamValue,
    Subckt,
    Value,
    validate,
)
from spicule.ir.expressions import format_expression
from spicule.sim import Simulation


def write(netlist: Netlist, *, bus_format: str = BUS_FORMAT, origins: bool = False) -> str:
    """
    Write `netlist` as CDL text: every subcircuit as a `.SUBCKT`, nothing at the top level. The arguments shared with
    other writers mean the same there.

    - `bus_format` spells bus bits, with `{name}` and `{index}`.
    - `origins=True` writes each cell's and instance's `meta.origin` as a comment.

    Every instance name gets its element letter in front (`mn` becomes `Mmn`), since Calibre reads the element
    type from the first letter.
    """
    if isinstance(netlist, Simulation):
        raise WriterError("CDL has no analyses, so it can't write a simulation: write its netlist")
    validate(netlist)
    by_name = {cell.name: cell for cell in netlist.cells}
    subckts = [cell for cell in netlist.cells if isinstance(cell, Subckt)]
    _check(subckts, by_name)

    lines = ["* Generated by spicule", ""]
    for cell in subckts:
        lines += _subckt(cell, by_name, bus_format, origins)
        lines.append("")
    lines.append(".END")
    lines.append("")
    return "\n".join(lines)


def _letter(target: Cell) -> str:
    if isinstance(target, Subckt):
        return "X"
    if target.element is Element.BUILTIN:
        return BUILTINS[target.name][0]
    return LETTERS[target.element]


def _check(written: list[Subckt], by_name: dict[str, Cell]) -> None:
    """Writer checks: built-ins, and names that differ only in case (Calibre folds case)."""
    _unique_folded("cell", [c.name for c in by_name.values()], None)
    for cell in written:
        _unique_folded("net", [net.name for net in cell.ports + cell.signals], cell.name)
        _unique_folded("parameter", [decl.name for decl in cell.params], cell.name)
        for inst in cell.instances:
            target = by_name[inst.cell]
            if isinstance(target, External) and target.element is Element.BUILTIN and target.name not in BUILTINS:
                raise WriterError(f"{target.name!r} is not a CDL built-in (known: {', '.join(BUILTINS)})")
        _unique_folded("instance", [_letter(by_name[i.cell]) + i.name for i in cell.instances], cell.name)


def _unique_folded(what: str, names: list[str], cell: str | None) -> None:
    seen: dict[str, str] = {}
    for name in names:
        other = seen.setdefault(name.lower(), name)
        if other != name:
            where = f"cell {cell!r}: " if cell else ""
            raise WriterError(f"{where}{what} names {other!r} and {name!r} are the same to Calibre (case-insensitive)")


def _subckt(cell: Subckt, by_name: dict[str, Cell], bus_format: str, origins: bool) -> list[str]:
    names = NetNames(cell, bus_format)
    params = "".join(f" {_decl(decl)}" for decl in cell.params)
    lines = []
    if origins and cell.meta.origin:
        lines.append(f"* origin: {cell.meta.origin}")
    lines.append(f".SUBCKT {cell.name} {' '.join(names.pins())}{params}".rstrip())
    for inst in cell.instances:
        lines += _instance(inst, by_name, names, origins)
    lines.append(f".ENDS {cell.name}")
    return lines


def _instance(inst: Instance, by_name: dict[str, Cell], names: NetNames, origins: bool) -> list[str]:
    target = by_name[inst.cell]
    letter = _letter(target)
    if isinstance(target, External) and target.element is Element.BUILTIN:
        # Ideal element: its value in place of a model name.
        value_name = BUILTINS[target.name][1]
        values = {p.name: p.value for p in inst.params}
        if value_name not in values:
            raise WriterError(f"instance {inst.name!r}: CDL built-in {target.name!r} needs {value_name}")
        rest = "".join(f" {_param(p)}" for p in inst.params if p.name != value_name)
        master = _value(values[value_name])
    else:
        rest = "".join(f" {_param(p)}" for p in inst.params)
        master = target.name
    lines = []
    if origins and inst.meta.origin:
        lines.append(f"* origin: {inst.meta.origin}")
    lines.append(f"{letter}{inst.name} {' '.join(names.nodes(inst, target))} {master}{rest}")
    return lines


def _decl(decl: ParamDecl) -> str:
    return f"{decl.name}={_value(decl.default)}"


def _param(param: ParamValue) -> str:
    return f"{param.name}={_value(param.value)}"


def _value(value: Value) -> str:
    """A plain number as is, other expressions in single quotes, strings in double quotes."""
    if isinstance(value, Expression):
        text = format_expression(value, functions=FUNCTIONS)
        return text if _is_plain_number(value) else f"'{text}'"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _is_plain_number(value: Expression) -> bool:
    return isinstance(value.root, Number)
