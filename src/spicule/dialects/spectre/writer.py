"""The Spectre writer: a validated netlist as a library of subcircuits, or a validated simulation as a deck."""

from spicule.dialects.common import NetNames, WriterError
from spicule.dialects.spectre.syntax import (
    ANALYSES,
    ANALYSES_WITH_CHILDREN,
    BUILTINS,
    BUS_FORMAT,
    CONSTANTS,
    KEYWORDS,
    MULTIPLICITY,
    RESERVED,
)
from spicule.ir import (
    Cell,
    Element,
    Expression,
    External,
    Instance,
    Neg,
    Netlist,
    Number,
    ParamDecl,
    ParamRef,
    ParamValue,
    Subckt,
    Value,
    is_identifier,
    validate,
)
from spicule.ir.expressions import format_expression, number, param_refs
from spicule.sim import Analysis, Options, Param, Raw, Simulation, SimValue
from spicule.sim import validate as validate_simulation

#: Names no cell or instance may have.
_NO_CELL_NAMES = KEYWORDS | CONSTANTS

_HEADER = ["// Generated by spicule", "simulator lang=spectre"]


def write(design: Netlist | Simulation, *, bus_format: str = BUS_FORMAT, origins: bool = False) -> str:
    """
    Write `design` as Spectre text.

    - A `Netlist` becomes a library: every subcircuit, nothing at the top level.
    - A `Simulation` becomes a deck to run: its parameters and includes, the subcircuits below its top cell, the top
      cell's instances at the top level with its ground net as `0`, then raw lines, options, saves and analyses.
    - `bus_format` spells bus bits, with `{name}` and `{index}`.
    - `origins=True` writes each cell's and instance's `meta.origin` as a comment.
    """
    if isinstance(design, Simulation):
        return _deck(design, bus_format, origins)
    validate(design)
    _check_names(design)
    by_name = {cell.name: cell for cell in design.cells}
    lines = [*_HEADER, ""]
    for cell in design.cells:
        if isinstance(cell, Subckt):
            lines += _subckt(cell, by_name, bus_format, origins)
            lines.append("")
    return "\n".join(lines)


def _deck(simulation: Simulation, bus_format: str, origins: bool) -> str:
    validate_simulation(simulation)
    _check_names(simulation.netlist)
    _check_statements(simulation)
    top_cell = simulation.top_cell
    by_name = {cell.name: cell for cell in simulation.netlist.cells}

    lines = [*_HEADER, ""]
    setup = []
    if simulation.top_params:
        setup.append(f"parameters {' '.join(_decl(decl) for decl in simulation.top_params)}")
    for include in simulation.includes:
        section = f" section={include.section}" if include.section else ""
        setup.append(f"include {_quoted(include.path)}{section}")
    if setup:
        lines += [*setup, ""]
    for cell in simulation.cells:
        lines += _subckt(cell, by_name, bus_format, origins)
        lines.append("")
    lines.append(f"// top: {top_cell.name}")
    names = NetNames(top_cell, bus_format, simulation.ground)
    for inst in top_cell.instances:
        lines += _instance(inst, by_name, names, origins, indent="")
    lines.append("")
    if simulation.raw:
        lines += [*(line for text in simulation.raw for line in text.splitlines()), ""]
    control = []
    if simulation.options is not None:
        control.append(_options(simulation.options))
    if simulation.saves:
        control.append(f"save {' '.join(simulation.saves)}")
    if control:
        lines += [*control, ""]
    if simulation.analyses:
        for item in simulation.analyses:
            lines += _statement(item, indent="")
        lines.append("")
    return "\n".join(lines)


def _check_statements(simulation: Simulation) -> None:
    if simulation.options is not None and simulation.options.name in _NO_CELL_NAMES:
        raise WriterError(f"options name {simulation.options.name!r} is a Spectre keyword")
    pending = list(simulation.analyses)
    while pending:
        item = pending.pop()
        if isinstance(item, Raw):
            continue
        if item.name in _NO_CELL_NAMES:
            raise WriterError(f"analysis name {item.name!r} is a Spectre keyword")
        if item.type not in ANALYSES:
            raise WriterError(f"analysis {item.name}: {item.type!r} is not a Spectre analysis")
        if item.children and item.type not in ANALYSES_WITH_CHILDREN:
            raise WriterError(f"analysis {item.name}: a {item.type} has no child analyses")
        pending += item.children


def _check_names(netlist: Netlist) -> None:
    for cell in netlist.cells:
        if cell.name in _NO_CELL_NAMES:
            raise WriterError(f"cell name {cell.name!r} is a Spectre keyword")
        if isinstance(cell, External) and cell.element is Element.BUILTIN and cell.name not in BUILTINS:
            raise WriterError(f"{cell.name!r} is not a Spectre built-in (known: {', '.join(sorted(BUILTINS))})")
        if not isinstance(cell, Subckt):
            continue
        # Only our own subcircuit parameters go on a `parameters` line. External ones are Spectre's (vsource freq).
        for decl in cell.params:
            if decl.name in CONSTANTS | RESERVED:
                raise WriterError(f"cell {cell.name!r}: parameter name {decl.name!r} is reserved in Spectre")
        for net in cell.ports + cell.signals:
            if net.name in CONSTANTS:
                raise WriterError(f"cell {cell.name!r}: net name {net.name!r} is a Spectre constant")
        for inst in cell.instances:
            if inst.name in _NO_CELL_NAMES:
                raise WriterError(f"cell {cell.name!r}: instance name {inst.name!r} is a Spectre keyword")


def _subckt(cell: Subckt, by_name: dict[str, Cell], bus_format: str, origins: bool) -> list[str]:
    names = NetNames(cell, bus_format)
    lines = []
    if origins and cell.meta.origin:
        lines.append(f"// origin: {cell.meta.origin}")
    lines.append(f"subckt {cell.name} ({' '.join(names.pins())})")
    params = [decl for decl in cell.params if decl.name != MULTIPLICITY]
    _check_multiplicity(cell)
    if params:
        lines.append(f"    parameters {' '.join(_decl(decl) for decl in params)}")
    for inst in cell.instances:
        lines += _instance(inst, by_name, names, origins, indent="    ")
    lines.append(f"ends {cell.name}")
    return lines


def _check_multiplicity(cell: Subckt) -> None:
    """Spectre's `m` is implicit on every subcircuit, defaults to 1 and can't be used in expressions inside."""
    for decl in cell.params:
        if decl.name == MULTIPLICITY and decl.default != number("1"):
            raise WriterError(f"cell {cell.name!r}: Spectre's implicit m always defaults to 1")
    values: list[Value] = [decl.default for decl in cell.params]
    values += [p.value for inst in cell.instances for p in inst.params]
    for value in values:
        if isinstance(value, Expression) and MULTIPLICITY in param_refs(value):
            raise WriterError(f"cell {cell.name!r}: Spectre doesn't allow m in expressions inside a subcircuit")


def _instance(inst: Instance, by_name: dict[str, Cell], names: NetNames, origins: bool, indent: str) -> list[str]:
    target = by_name[inst.cell]
    params = "".join(f" {_param(p)}" for p in inst.params)
    lines = []
    if origins and inst.meta.origin:
        lines.append(f"{indent}// origin: {inst.meta.origin}")
    lines.append(f"{indent}{inst.name} ({' '.join(names.nodes(inst, target))}) {target.name}{params}")
    return lines


def _options(options: Options) -> str:
    return f"{options.name} options{_params(options.params)}"


def _statement(item: Analysis | Raw, indent: str) -> list[str]:
    if isinstance(item, Raw):
        return [f"{indent}{line}" for line in item.text.splitlines()]
    head = f"{indent}{item.name} {item.type}{_params(item.params)}"
    if item.type not in ANALYSES_WITH_CHILDREN:
        return [head]
    children = [line for child in item.children for line in _statement(child, f"{indent}    ")]
    return [f"{head} {{", *children, f"{indent}}}"]


def _params(params: tuple[Param, ...]) -> str:
    return "".join(f" {param.name}={_sim_value(param.value)}" for param in params)


def _sim_value(value: SimValue) -> str:
    if isinstance(value, tuple):
        return f"[{' '.join(_vector_item(item) for item in value)}]"
    return _value(value)


def _vector_item(value: Value) -> str:
    """In a vector, anything but a constant, a parameter or a unary of those needs parentheses: `[1 -w (2*w)]`."""
    if isinstance(value, Expression):
        root = value.root.operand if isinstance(value.root, Neg) else value.root
        if not isinstance(root, Number | ParamRef):
            return f"({format_expression(value)})"
    return _value(value)


def _decl(decl: ParamDecl) -> str:
    return f"{decl.name}={_value(decl.default)}"


def _param(param: ParamValue) -> str:
    return f"{param.name}={_value(param.value)}"


def _value(value: Value) -> str:
    if isinstance(value, Expression):
        return format_expression(value)
    if is_identifier(value):  # Spectre leaves strings that look like names unquoted (type=dc).
        return value
    return _quoted(value)


def _quoted(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'
