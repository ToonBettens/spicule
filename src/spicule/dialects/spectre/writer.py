"""The Spectre writer: a validated netlist as a Spectre netlist."""

from spicule.dialects.common import IDENTIFIER, NetNames, WriterError, cells_to_write, check_ground
from spicule.dialects.spectre.syntax import BUILTINS, BUS_FORMAT, CONSTANTS, KEYWORDS, MULTIPLICITY, RESERVED
from spicule.ir import Element, Expression, External, Instance, Netlist, ParamDecl, ParamValue, Subckt, Value, validate
from spicule.ir.connections import bits, nets, signal_bits
from spicule.ir.expressions import format_expression, number, param_refs


def write(
    netlist: Netlist,
    *,
    top: str | None = None,
    ground: str | None = None,
    bus_format: str = BUS_FORMAT,
    origins: bool = False,
) -> str:
    """
    Write `netlist` as Spectre text.

    - `top=None` writes every subcircuit. `top="tb"` writes the subcircuits below `tb` and `tb`'s own instances at the top level.
    - `ground` names a scalar net of the top cell that is written as `0`, Spectre's reference node.
    - `bus_format` spells bus bits, with `{name}` and `{index}`.
    - `origins=True` writes each cell's and instance's `meta.origin` as a comment.
    """
    validate(netlist)
    by_name = {cell.name: cell for cell in netlist.cells}
    defined, top_cell = cells_to_write(netlist, top)
    check_ground(top_cell, ground)
    _check_names(netlist)

    lines = ["// Generated by spicule", "simulator lang=spectre", ""]
    for cell in defined:
        lines += _subckt(cell, by_name, bus_format, origins)
        lines.append("")
    if top_cell is not None:
        lines.append(f"// top: {top_cell.name}")
        names = NetNames(top_cell, bus_format, ground)
        for inst in top_cell.instances:
            lines += _instance(inst, by_name, names, origins, indent="")
        lines.append("")
    return "\n".join(lines)


def _check_names(netlist: Netlist) -> None:
    for cell in netlist.cells:
        if cell.name in KEYWORDS | CONSTANTS:
            raise WriterError(f"cell name {cell.name!r} is a Spectre keyword")
        if isinstance(cell, External) and cell.element is Element.BUILTIN and cell.name not in BUILTINS:
            raise WriterError(f"{cell.name!r} is not a Spectre built-in (known: {', '.join(sorted(BUILTINS))})")
        if not isinstance(cell, Subckt):
            continue
        # Only our own subcircuit parameters go on a `parameters` line. External ones are Spectre's (vsource freq).
        for decl in cell.params:
            if decl.name in CONSTANTS | RESERVED:
                raise WriterError(f"cell {cell.name!r}: parameter name {decl.name!r} is reserved in Spectre")
        for net in cell.ports + cell.signals:
            if net.name in CONSTANTS:
                raise WriterError(f"cell {cell.name!r}: net name {net.name!r} is a Spectre constant")
        for inst in cell.instances:
            if inst.name in KEYWORDS | CONSTANTS:
                raise WriterError(f"cell {cell.name!r}: instance name {inst.name!r} is a Spectre keyword")


def _subckt(cell: Subckt, by_name: dict, bus_format: str, origins: bool) -> list[str]:
    names = NetNames(cell, bus_format)
    pins = [names.names[bit] for port in cell.ports for bit in signal_bits(port)]
    lines = []
    if origins and cell.meta.origin:
        lines.append(f"// origin: {cell.meta.origin}")
    lines.append(f"subckt {cell.name} ({' '.join(pins)})")
    params = [decl for decl in cell.params if decl.name != MULTIPLICITY]
    _check_multiplicity(cell)
    if params:
        lines.append(f"    parameters {' '.join(_decl(decl) for decl in params)}")
    for inst in cell.instances:
        lines += _instance(inst, by_name, names, origins, indent="    ")
    lines.append(f"ends {cell.name}")
    return lines


def _check_multiplicity(cell: Subckt) -> None:
    """Spectre's `m` is implicit on every subcircuit, defaults to 1 and can't be used in expressions inside."""
    for decl in cell.params:
        if decl.name == MULTIPLICITY and decl.default is not None and decl.default != number("1"):
            raise WriterError(f"cell {cell.name!r}: Spectre's implicit m always defaults to 1")
    values: list[Value] = [decl.default for decl in cell.params if decl.default is not None]
    values += [p.value for inst in cell.instances for p in inst.params]
    for value in values:
        if isinstance(value, Expression) and MULTIPLICITY in param_refs(value):
            raise WriterError(f"cell {cell.name!r}: Spectre doesn't allow m in expressions inside a subcircuit")


def _instance(inst: Instance, by_name: dict, names: NetNames, origins: bool, indent: str) -> list[str]:
    target = by_name[inst.cell]
    cell_nets = nets(names.cell)
    pieces = {conn.port: conn.pieces for conn in inst.connections}
    nodes = [name for port in target.ports for name in names.of(bits(pieces[port.name], cell_nets), inst)]
    params = "".join(f" {_param(p)}" for p in inst.params)
    lines = []
    if origins and inst.meta.origin:
        lines.append(f"{indent}// origin: {inst.meta.origin}")
    lines.append(f"{indent}{inst.name} ({' '.join(nodes)}) {target.name}{params}")
    return lines


def _decl(decl: ParamDecl) -> str:
    return decl.name if decl.default is None else f"{decl.name}={_value(decl.default)}"


def _param(param: ParamValue) -> str:
    return f"{param.name}={_value(param.value)}"


def _value(value: Value) -> str:
    if isinstance(value, Expression):
        return format_expression(value)
    if IDENTIFIER.match(value):
        return value
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'
